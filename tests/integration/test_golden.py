def _compare_cells(
    ws_actual: openpyxl.worksheet.worksheet.Worksheet,
    ws_expected: openpyxl.worksheet.worksheet.Worksheet,
) -> list[str]:
    """Compare cells in the used range of two worksheets.

    Args:
        ws_actual: Worksheet from the freshly filled output.
        ws_expected: Worksheet from the golden copy.

    Returns:
        A list of difference messages (empty if identical).

    """
    diffs: list[str] = []
    sheet_name = ws_actual.title

    # Merged cells
    actual_merged = {str(r) for r in ws_actual.merged_cells.ranges}
    expected_merged = {str(r) for r in ws_expected.merged_cells.ranges}
    if actual_merged != expected_merged:
        only_actual = actual_merged - expected_merged
        only_expected = expected_merged - actual_merged
        if only_actual:
            diffs.append(f"[{sheet_name}] Extra merged ranges: {sorted(only_actual)}")
        if only_expected:
            diffs.append(f"[{sheet_name}] Missing merged ranges: {sorted(only_expected)}")

    # Cell-by-cell in the combined used range
    max_row = max(ws_actual.max_row or 0, ws_expected.max_row or 0)
    max_col = max(ws_actual.max_column or 0, ws_expected.max_column or 0)

    for row in range(1, max_row + 1):
        for col in range(1, max_col + 1):
            c_act = ws_actual.cell(row=row, column=col)
            c_exp = ws_expected.cell(row=row, column=col)

            # Skip empty cells in both
            if c_act.value is None and c_exp.value is None:
                continue
            if c_act.value == c_exp.value:
                continue

            # Value mismatch — try tolerant comparison
            v_act = c_act.value
            v_exp = c_exp.value

            ref = f"{c_act.column_letter}{row}"

            # Both None → already handled above
            if v_act is None and v_exp is not None:
                diffs.append(f"[{sheet_name}] {ref}: actual=None, expected={v_exp!r}")
                continue
            if v_act is not None and v_exp is None:
                diffs.append(f"[{sheet_name}] {ref}: actual={v_act!r}, expected=None")
                continue

            # openpyxl internal objects (ArrayFormula, etc.) may not
            # implement __eq__ properly — compare by content attributes.
            if type(v_act) is not type(v_exp):
                diffs.append(
                    f"[{sheet_name}] {ref}: type mismatch "
                    f"{type(v_act).__name__} != {type(v_exp).__name__}",
                )
                continue
            if not isinstance(
                v_act,
                (
                    str,
                    int,
                    float,
                    bool,
                    bytes,
                    type(None),
                    datetime,
                    date,
                    time,
                    dt_module.timedelta,
                    Decimal,
                ),
            ):
                # Try common content attributes for openpyxl internal objects
                if hasattr(v_act, "text") and hasattr(v_exp, "text"):
                    if v_act.text != v_exp.text:
                        diffs.append(
                            f"[{sheet_name}] {ref}: text mismatch: "
                            f"{v_act.text!r} vs {v_exp.text!r}",
                        )
                    continue
                # Fallback: compare by repr
                if repr(v_act) != repr(v_exp):
                    diffs.append(f"[{sheet_name}] {ref}: repr mismatch: {v_act!r} vs {v_exp!r}")
                continue

            # Number format
            nf_act = c_act.number_format
            nf_exp = c_exp.number_format
            if nf_act != nf_exp:
                diffs.append(f"[{sheet_name}] {ref}: number_format {nf_act!r} != {nf_exp!r}")

            # Bool tolerance (COM may return 1/0)
            if isinstance(v_act, bool) and isinstance(v_exp, bool):
                continue  # both bool, already checked equality above
            if (
                isinstance(v_act, (int, float))
                and isinstance(v_exp, (int, float))
                and bool(v_act) == bool(v_exp)
            ):
                continue  # bool-like comparison

            # Numeric tolerance
            if (
                isinstance(v_act, (int, float))
                and isinstance(v_exp, (int, float))
                and abs(float(v_act) - float(v_exp)) < 1e-10
            ):
                continue

            diffs.append(
                f"[{sheet_name}] {ref}: actual={v_act!r} (type={type(v_act).__name__}), "
                f"expected={v_exp!r} (type={type(v_exp).__name__})",
            )

    return diffs


def _compare_tables(
    wb_actual: openpyxl.Workbook,
    wb_expected: openpyxl.Workbook,
) -> list[str]:
    """Compare all Excel table definitions between two workbooks.

    Returns:
        A list of difference messages (empty if identical).

    """
    diffs: list[str] = []

    # Gather tables from both workbooks
    def _get_tables(wb: openpyxl.Workbook) -> dict[str, tuple[str, str, list[str]]]:
        result: dict[str, tuple[str, str, list[str]]] = {}
        for ws in wb.worksheets:
            for table in ws._tables.values():
                cols = [c.name for c in table.tableColumns]
                result[table.displayName] = (ws.title, table.ref, cols)
        return result

    tables_act = _get_tables(wb_actual)
    tables_exp = _get_tables(wb_expected)

    # Check expected tables exist in actual
    for name, (sheet, ref, cols) in tables_exp.items():
        if name not in tables_act:
            diffs.append(f"Table {name!r} missing in actual output")
            continue
        act_sheet, act_ref, act_cols = tables_act[name]
        if act_sheet != sheet:
            diffs.append(f"Table {name!r}: sheet {act_sheet!r} != expected {sheet!r}")
        if act_ref != ref:
            diffs.append(f"Table {name!r}: ref {act_ref!r} != expected {ref!r}")
        if act_cols != cols:
            diffs.append(f"Table {name!r}: columns {act_cols} != expected {cols}")

    # Check for extra tables in actual
    diffs.extend(
        f"Unexpected table {name!r} in actual output"
        for name in tables_act
        if name not in tables_exp
    )

    return diffs


def _compare_defined_names(
    wb_actual: openpyxl.Workbook,
    wb_expected: openpyxl.Workbook,
) -> list[str]:
    """Compare defined names between two workbooks.

    Returns:
        A list of difference messages (empty if identical).

    """
    diffs: list[str] = []

    def _get_names(wb: openpyxl.Workbook) -> dict[str, list[str]]:
        result: dict[str, list[str]] = {}
        for name_obj in wb.defined_names.values():
            destinations = list(name_obj.destinations)
            result[name_obj.name] = [f"{ws}!{addr}" for ws, addr in destinations]
        return result

    names_act = _get_names(wb_actual)
    names_exp = _get_names(wb_expected)

    # Ignore internal chart names (_xlchart.*)
    names_act = {k: v for k, v in names_act.items() if not k.startswith("_")}
    names_exp = {k: v for k, v in names_exp.items() if not k.startswith("_")}

    if names_act != names_exp:
        diffs.append(f"Defined names mismatch: actual={names_act}, expected={names_exp}")

    return diffs


def _compare_sheets(
    wb_actual: openpyxl.Workbook,
    wb_expected: openpyxl.Workbook,
) -> list[str]:
    """Compare sheet names and count.

    Returns:
        A list of difference messages (empty if identical).

    """
    diffs: list[str] = []
    if wb_actual.sheetnames != wb_expected.sheetnames:
        diffs.append(
            f"Sheet names differ: actual={wb_actual.sheetnames}, expected={wb_expected.sheetnames}",
        )
    return diffs


_CHART_PART_RE = re.compile(r"xl/charts/chart\d+\.xml")
_PIVOT_CACHE_RE = re.compile(r"xl/pivotCache/pivotCacheDefinition\d+\.xml")
_CHART_FORMULA_RE = re.compile(r"<(?:\w+:)?f>([^<]+)</(?:\w+:)?f>")


def _chart_formulas(path: Path) -> set[str]:
    """Every chart data reference in the package, ignoring the XML prefix."""
    formulas: set[str] = set()
    with zipfile.ZipFile(path) as archive:
        for name in archive.namelist():
            if _CHART_PART_RE.fullmatch(name):
                raw = archive.read(name).decode("utf-8", errors="replace")
                formulas.update(_CHART_FORMULA_RE.findall(raw))
    return formulas


_CHART_KIND_RE = re.compile(
    r"<(?:\w+:)?(barChart|lineChart|scatterChart|areaChart|pieChart|doughnutChart)>"
)
_AXIS_POS_RE = re.compile(r'axPos val="(\w+)"')


def _chart_axis_positions(path: Path) -> dict[str, tuple[list[str], list[str]]]:
    """Chart kind and ``axPos`` values of every chart part, keyed by part name."""
    charts: dict[str, tuple[list[str], list[str]]] = {}
    with zipfile.ZipFile(path) as archive:
        for name in sorted(archive.namelist()):
            if _CHART_PART_RE.fullmatch(name):
                raw = archive.read(name).decode("utf-8", errors="replace")
                charts[name] = (
                    _CHART_KIND_RE.findall(raw),
                    _AXIS_POS_RE.findall(raw),
                )
    return charts


def test_scatter_and_combo_axes_survive_a_fill(
    charts_template_2: Path,
    output_path: Path,
) -> None:
    """Chart-axis repair keeps every axis in place, including secondary ones."""
    fill(template=charts_template_2, output=output_path, tables=_chart_tables_data())

    template_axes = _chart_axis_positions(charts_template_2)
    output_axes = _chart_axis_positions(output_path)

    assert set(output_axes) == set(template_axes)
    for part, (kinds, positions) in template_axes.items():
        output_kinds, output_positions = output_axes[part]
        assert output_kinds == kinds, part
        # Only the serialisation order of the axes may differ.
        assert sorted(output_positions) == sorted(positions), part
        if "scatterChart" in kinds:
            assert output_positions == ["b", "l"], part
        if "barChart" in kinds and "lineChart" in kinds:
            assert "r" in output_positions, part


def _pivot_refresh_flags(path: Path) -> list[bool]:
    """The ``refreshOnLoad`` flag of every pivot cache in the package."""
    with zipfile.ZipFile(path) as archive:
        return [
            bool(re.search(r'\brefreshOnLoad="(1|true)"', archive.read(name).decode("utf-8")))
            for name in sorted(archive.namelist())
            if _PIVOT_CACHE_RE.fullmatch(name)
        ]


def _compare_package_parts(actual_path: Path, expected_path: Path) -> list[str]:
    """Compare the parts openpyxl's object model cannot see.

    Cell values are compared through openpyxl above; chart data references and
    the pivot cache refresh flags only exist inside the zip package, so they
    are read straight from it.

    Returns:
        A list of difference messages (empty if identical).

    """
    diffs: list[str] = []

    actual_formulas = _chart_formulas(actual_path)
    expected_formulas = _chart_formulas(expected_path)
    if actual_formulas != expected_formulas:
        only_actual = sorted(actual_formulas - expected_formulas)
        only_expected = sorted(expected_formulas - actual_formulas)
        if only_actual:
            diffs.append(f"Extra chart references: {only_actual}")
        if only_expected:
            diffs.append(f"Missing chart references: {only_expected}")

    actual_flags = _pivot_refresh_flags(actual_path)
    expected_flags = _pivot_refresh_flags(expected_path)
    if actual_flags != expected_flags:
        diffs.append(
            f"Pivot refreshOnLoad flags differ: actual={actual_flags}, expected={expected_flags}",
        )

    return diffs


def _assert_workbooks_match(actual_path: Path, expected_path: Path) -> None:
    """Assert that two workbooks are identical in structure and content."""
    wb_actual = openpyxl.load_workbook(actual_path)
    wb_expected = openpyxl.load_workbook(expected_path)

    all_diffs: list[str] = []

    try:
        all_diffs.extend(_compare_sheets(wb_actual, wb_expected))
        all_diffs.extend(_compare_tables(wb_actual, wb_expected))
        all_diffs.extend(_compare_defined_names(wb_actual, wb_expected))
        all_diffs.extend(_compare_package_parts(actual_path, expected_path))

        # Cell-by-cell comparison for each sheet
        sheet_names = wb_actual.sheetnames
        for sheet_name in sheet_names:
            ws_act = wb_actual[sheet_name]
            ws_exp = wb_expected[sheet_name]
            all_diffs.extend(_compare_cells(ws_act, ws_exp))
    finally:
        wb_actual.close()
        wb_expected.close()

    if all_diffs:
        msg = "Golden copy mismatch:\n" + "\n".join(f"  {d}" for d in all_diffs)
        raise AssertionError(msg)


