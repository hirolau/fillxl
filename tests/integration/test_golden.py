class TestGoldenCopyRegression:
    """Fresh fills match their golden copies cell-by-cell."""

    @pytest.mark.parametrize(
        ("test_id", "template_file", "golden_file", "engine", "fill_kwargs"),
        [pytest.param(*d, id=d[0]) for d in _TEMPLATE_DEFS],
    )
    def test_openpyxl_matches_golden(
        self,
        test_id: str,
        template_file: str,
        golden_file: str,
        engine: Engine,
        fill_kwargs: dict[str, Any],
        tmp_path: Path,
    ) -> None:
        """A template filled via the openpyxl backend matches its golden copy."""
        golden = GOLDEN / engine / golden_file
        if not golden.exists():
            pytest.skip(f"Golden copy not found: {golden}")

        output = tmp_path / golden_file
        fill(
            template=ASSETS / template_file,
            output=output,
            engine=engine,
            **fill_kwargs,
        )
        _assert_workbooks_match(output, golden)

